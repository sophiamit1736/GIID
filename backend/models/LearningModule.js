const mongoose = require("mongoose");

const learningModuleSchema = new mongoose.Schema(
  {
    moduleId: {
      type: String,
      required: true,
      unique: true,
      trim: true,
    },

    title: {
      type: String,
      required: true,
      trim: true,
    },

    description: {
      type: String,
      required: true,
    },

    category: {
      type: String,
      enum: [
        "ADL",
        "Academic",
        "Motor",
        "Language",
        "Vocational",
        "Therapeutic",
        "Specialized Care",
      ],
      required: true,
    },

    skill: {
      type: String,
      required: true,
    },

    facpDomain: {
      type: String,
      default: "",
      index: true,
    },

    facpItemCodes: {
      type: [String],
      default: [],
    },

    // FACP functional levels for which this module is curriculum-appropriate.
    // This is separate from the learner's Beginner/Intermediate/Advanced
    // learningLevel, which controls difficulty.
    facpLevels: {
      type: [String],
      default: [],
      index: true,
    },

    level: {
      type: String,
      enum: ["Beginner", "Intermediate", "Advanced"],
      default: "Beginner",
    },

    duration: {
      type: Number,
      default: 10,
    },

    ageGroups: {
      type: [String],
      default: [],
    },

    objectives: {
      type: [String],
      default: [],
    },

    steps: {
      type: [String],
      default: [],
    },

    visuals: {
      type: [String],
      default: [],
    },

    audioText: {
      type: [String],
      default: [],
    },

    activities: {
      type: [
        {
          type: {
            type: String,
            default: "instruction",
          },
          question: {
            type: String,
            default: "",
          },
          options: {
            type: [String],
            default: [],
          },
          answer: {
            type: String,
            default: "",
          },
          image: {
            type: String,
            default: "",
          },
        },
      ],
      default: [],
    },

    // Machine-readable game configuration generated by the activity generator.
    // Kept flexible so new game types can be added without changing MongoDB schema.
    gameConfig: {
      type: mongoose.Schema.Types.Mixed,
      default: null,
    },

    adaptations: {
      type: [String],
      default: [],
    },

    /*
     * Child-friendly learning configuration
     */
    activityType: {
      type: String,
      enum: [
        "visual-sequence",
        "matching",
        "choice",
        "drag-sort",
        "memory",
        "movement",
        "communication",
        "vocational-practice",
        "routine",
      ],
      default: "visual-sequence",
    },

    /*
     * Visual content for every step.
     *
     * Example:
     * {
     *   title: "Take the toothbrush",
     *   instruction: "Pick up your toothbrush",
     *   emoji: "🪥",
     *   image: "/uploads/toothbrush.jpg",
     *   audioText: "Pick up your toothbrush",
     *   action: "tap"
     * }
     */
    interactiveSteps: [
      {
        title: String,
        instruction: String,
        tamil: String,
        emoji: String,
        image: String,
        video: String,
        audio: String,
        audioText: String,
        action: {
          type: mongoose.Schema.Types.Mixed,
          default: () => ({ type: "guided-step" }),
        },
        choices: [String],
        correctChoice: String,
      },
    ],

    /*
     * Optional module introduction media
     */
    coverImage: {
      type: String,
      default: "",
    },

    coverEmoji: {
      type: String,
      default: "🌱",
    },

    audioEnabled: {
      type: Boolean,
      default: true,
    },

    icon: {
      type: String,
      default: "school",
    },

    color: {
      type: String,
      default: "#1565C0",
    },

    generatedBy: { type: String, default: "manual" },
    generationSource: { type: String, default: "manual" },

    status: {
      type: String,
      enum: ["Active", "Inactive"],
      default: "Active",
    },
  },
  {
    timestamps: true,
  }
);

// Brushing Teeth uses one dedicated video per learning step.
// This prevents accidental video reuse when the module is updated.
learningModuleSchema.pre("validate", function () {
  if (this.moduleId === "adl-brushing" && Array.isArray(this.interactiveSteps)) {
    const videos = this.interactiveSteps.map((step) => step && step.video).filter(Boolean);
    const uniqueVideos = new Set(videos);
    if (videos.length !== 9 || uniqueVideos.size !== 9) {
      throw new Error("Brushing Teeth must contain exactly 9 unique video clips.");
    }
  }
});

module.exports = mongoose.model(
  "LearningModule",
  learningModuleSchema
);